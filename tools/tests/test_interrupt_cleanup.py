"""Check interrupted input generation, fixture publication and lock acquisition."""

import importlib.util
import json
import os
import tempfile
import unittest
from pathlib import Path
from unittest import mock


def load_tool(relative):
    """Load a tool from this checkout or the explicit baseline tools directory."""
    root = Path(os.environ.get("TORCUL_TOOLS_DIR", Path(__file__).resolve().parents[1]))
    spec = importlib.util.spec_from_file_location(Path(relative).stem, root / relative)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


BACKENDS = load_tool("bench/backends.py")
FIXTURES = load_tool("fixtures/track_fixtures.py")


class RawInputTests(unittest.TestCase):
    """Check raw input cleanup without invoking FFmpeg."""

    def test_replace_failure_removes_partial(self):
        """A publication error removes generated bytes and propagates unchanged."""
        with tempfile.TemporaryDirectory() as directory:
            work = Path(directory)
            partial = work / f"src_1080p_{BACKENDS.RAW_FRAMES}f.y4m.partial"
            error = OSError("replace failed")
            with (
                mock.patch.object(
                    BACKENDS,
                    "run_tool",
                    side_effect=lambda *a, **k: partial.write_bytes(b"raw"),
                ),
                mock.patch.object(BACKENDS.os, "replace", side_effect=error),
                self.assertRaises(OSError) as raised,
            ):
                BACKENDS.raw_input(work)
            self.assertIs(raised.exception, error)
            self.assertFalse(partial.exists())
            self.assertFalse(partial.with_suffix("").exists())

    def test_generation_interrupt_removes_partial(self):
        """An interrupted generator removes bytes written before the interrupt."""
        with tempfile.TemporaryDirectory() as directory:
            work = Path(directory)
            partial = work / f"src_1080p_{BACKENDS.RAW_FRAMES}f.y4m.partial"
            error = KeyboardInterrupt("generation interrupted")

            def interrupt(*args, **kwargs):
                """Simulate generation writing bytes before interruption."""
                partial.write_bytes(b"partial")
                raise error

            with (
                mock.patch.object(BACKENDS, "run_tool", side_effect=interrupt),
                self.assertRaises(KeyboardInterrupt) as raised,
            ):
                BACKENDS.raw_input(work)
            self.assertIs(raised.exception, error)
            self.assertFalse(partial.exists())
            self.assertFalse(partial.with_suffix("").exists())

    def test_success_publishes_raw(self):
        """Successful generation returns the published file without a partial."""
        with tempfile.TemporaryDirectory() as directory:
            work = Path(directory)
            raw = work / f"src_1080p_{BACKENDS.RAW_FRAMES}f.y4m"
            partial = work / (raw.name + ".partial")
            with mock.patch.object(
                BACKENDS,
                "run_tool",
                side_effect=lambda *a, **k: partial.write_bytes(b"raw"),
            ):
                result = BACKENDS.raw_input(work)
            self.assertEqual(result, raw)
            self.assertEqual(raw.read_bytes(), b"raw")
            self.assertFalse(partial.exists())


class PublishTests(unittest.TestCase):
    """Check restoration and publication using real temporary directories."""

    def check_failed_publish(self, error, *, previous=True):
        """Fail the staging rename and verify restoration plus exception identity."""
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            out_dir = root / "output"
            staging = root / "staging"
            staging.mkdir()
            (staging / "content").write_bytes(b"new")
            if previous:
                out_dir.mkdir()
                (out_dir / "content").write_bytes(b"previous")
                (out_dir / "manifest.json").write_text(json.dumps({"policy": FIXTURES.POLICY}))
            rename = os.rename

            def fail_staging(source, destination):
                """Interrupt only publication, allowing backup and restoration."""
                if source == staging:
                    raise error
                return rename(source, destination)

            with (
                mock.patch.object(FIXTURES.os, "rename", side_effect=fail_staging),
                self.assertRaises(type(error)) as raised,
            ):
                FIXTURES.publish(staging, out_dir)
            self.assertIs(raised.exception, error)
            if previous:
                self.assertTrue(out_dir.is_dir())
                self.assertEqual((out_dir / "content").read_bytes(), b"previous")
            else:
                self.assertFalse(out_dir.exists())
            self.assertEqual((staging / "content").read_bytes(), b"new")
            self.assertEqual(list(root.glob(".output.old-*")), [])

    def test_interrupt_restores_previous(self):
        """An interrupted staging rename restores the previous fixture set."""
        self.check_failed_publish(KeyboardInterrupt("publication interrupted"))

    def test_oserror_restores_previous(self):
        """An ordinary staging rename error still restores the previous set."""
        self.check_failed_publish(OSError("publication failed"))

    def test_interrupt_without_previous_removes_holder(self):
        """An interrupted first publication leaves no output or empty holder."""
        self.check_failed_publish(
            KeyboardInterrupt("publication interrupted"), previous=False
        )

    def test_success_replaces_previous(self):
        """Successful publication replaces old content and removes the holder."""
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            out_dir = root / "output"
            out_dir.mkdir()
            (out_dir / "content").write_bytes(b"previous")
            (out_dir / "manifest.json").write_text(json.dumps({"policy": FIXTURES.POLICY}))
            staging = root / "staging"
            staging.mkdir()
            (staging / "content").write_bytes(b"new")
            FIXTURES.publish(staging, out_dir)
            self.assertEqual((out_dir / "content").read_bytes(), b"new")
            self.assertFalse(staging.exists())
            self.assertEqual(list(root.glob(".output.old-*")), [])


class LockWorkTests(unittest.TestCase):
    """Check descriptor cleanup for failures while acquiring the work lock."""

    def check_failed_lock(self, error):
        """Verify the real descriptor is closed and the original error propagates."""
        with (
            tempfile.TemporaryDirectory() as directory,
            mock.patch.object(BACKENDS.fcntl, "flock", side_effect=error) as flock,
            self.assertRaises(type(error)) as raised,
        ):
            BACKENDS.lock_work(Path(directory))
        self.assertIs(raised.exception, error)
        descriptor = flock.call_args.args[0]
        try:
            with self.assertRaises(OSError):
                os.fstat(descriptor)
        finally:
            try:
                os.close(descriptor)
            except OSError:
                pass

    def test_interrupt_closes_descriptor(self):
        """An interrupted lock acquisition releases its descriptor."""
        self.check_failed_lock(KeyboardInterrupt("lock interrupted"))

    def test_oserror_closes_descriptor(self):
        """An unexpected lock error releases its descriptor."""
        self.check_failed_lock(OSError("lock failed"))

    def test_contention_closes_descriptor_and_reports_holder(self):
        """Lock contention retains its diagnostic and closes the descriptor."""
        with tempfile.TemporaryDirectory() as directory:
            work = Path(directory)
            with (
                mock.patch.object(
                    BACKENDS.fcntl, "flock", side_effect=BlockingIOError
                ) as flock,
                self.assertRaises(RuntimeError) as raised,
            ):
                BACKENDS.lock_work(work)
            self.assertEqual(
                str(raised.exception), f"another run holds {work / '.bench.lock'}"
            )
            with self.assertRaises(OSError):
                os.fstat(flock.call_args.args[0])
