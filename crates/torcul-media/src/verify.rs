use crate::{
    Result,
    inspect::{self, Snapshot},
    packets::PacketProof,
};
use serde::{Deserialize, Serialize};
use std::path::Path;
use torcul_policy::{Plan, TrackKind, normalize_language};

/// Allow one 24-fps frame plus container timestamp rounding, in microseconds.
pub const DURATION_TOLERANCE_US: u64 = 50_000;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VerifyReport {
    pub pass: bool,
    pub failures: Vec<String>,
    pub source_packets: Vec<PacketProof>,
    pub staging_packets: Vec<PacketProof>,
    pub duration_tolerance_us: u64,
}

/// Re-probe both files; compare payload hashes and expected stream structure.
pub fn verify(src: &Path, plan: &Plan, staging: &Path) -> Result<VerifyReport> {
    let source = inspect::snapshot(src)?;
    let output = inspect::snapshot(staging)?;
    let mut failures = Vec::new();
    let kept = plan.kept_indices();
    if plan.decisions.len() != source.facts.tracks.len()
        || plan.decisions.iter().enumerate().any(|(i, d)| i != d.index)
    {
        failures.push("plan does not cover source in order".into());
    }
    if output.facts.tracks.len() != kept.len() {
        failures.push("stream-count".into());
    }
    for (to, from) in kept.iter().copied().enumerate() {
        compare_stream(&source, &output, plan, from, to, &mut failures);
    }
    if !duration_within_tolerance(source.duration_us, output.duration_us) {
        failures.push("duration".into());
    }
    if source.chapters != output.chapters {
        failures.push("chapters".into());
    }
    compare_tags(&source.tags, &output.tags, "global-metadata", &mut failures);
    Ok(VerifyReport {
        pass: failures.is_empty(),
        failures,
        source_packets: source.packets,
        staging_packets: output.packets,
        duration_tolerance_us: DURATION_TOLERANCE_US,
    })
}
fn compare_stream(
    src: &Snapshot,
    out: &Snapshot,
    plan: &Plan,
    from: usize,
    to: usize,
    failures: &mut Vec<String>,
) {
    let Some(source) = src.facts.tracks.get(from) else {
        failures.push(format!("invalid source index {from}"));
        return;
    };
    let Some(target) = out.facts.tracks.get(to) else {
        failures.push(format!("missing stream {to}"));
        return;
    };
    let mut expected = source.clone();
    expected.index = to;
    if plan.default_audio_change.is_some_and(|(_, i)| i == from) {
        expected.dispositions.insert("default".into());
    }
    // Matroska/MP4 may canonicalize synonymous language codes.
    expected.language = expected.language.as_deref().map(language_key);
    let mut actual = target.clone();
    actual.language = actual.language.as_deref().map(language_key);
    if expected != actual {
        failures.push(format!(
            "stream-{to}-structure: expected {expected:?}; actual {actual:?}"
        ));
    }
    if src.packets[from] != out.packets[to] {
        failures.push(format!(
            "stream-{to}-payload: source {:?}; staging {:?}",
            src.packets[from], out.packets[to]
        ));
    }
    if (source.kind == TrackKind::Attachment || source.attached_pic)
        && src.extra[from] != out.extra[to]
    {
        failures.push(format!("stream-{to}-attachment-data"));
    }
    compare_tags(
        &src.stream_tags[from],
        &out.stream_tags[to],
        &format!("stream-{to}-metadata"),
        failures,
    );
}
fn compare_tags(
    source: &inspect::Tags,
    target: &inspect::Tags,
    label: &str,
    failures: &mut Vec<String>,
) {
    // Per-stream duration measurements are regenerated by the container.
    for (key, value) in source
        .iter()
        .filter(|(key, _)| !(label.starts_with("stream-") && key.eq_ignore_ascii_case("duration")))
    {
        let same = if key.eq_ignore_ascii_case("language") {
            target
                .get(key)
                .is_some_and(|v| language_key(v) == language_key(value))
        } else {
            target.get(key) == Some(value)
        };
        if !same {
            failures.push(format!("{label}:{key}"));
        }
    }
}
pub fn duration_within_tolerance(a: Option<i64>, b: Option<i64>) -> bool {
    match (a, b) {
        (Some(a), Some(b)) => a.abs_diff(b) <= DURATION_TOLERANCE_US,
        (None, None) => true,
        _ => false,
    }
}

impl VerifyReport {
    pub fn failed(message: String) -> Self {
        Self {
            pass: false,
            failures: vec![message],
            source_packets: vec![],
            staging_packets: vec![],
            duration_tolerance_us: DURATION_TOLERANCE_US,
        }
    }
}

fn language_key(value: &str) -> String {
    let (base, suffix) = value.trim().split_once('-').unwrap_or((value.trim(), ""));
    let normalized = normalize_language(base).unwrap_or_else(|| base.to_ascii_lowercase());
    if suffix.is_empty() {
        normalized
    } else {
        format!("{normalized}-{}", suffix.to_ascii_lowercase())
    }
}
